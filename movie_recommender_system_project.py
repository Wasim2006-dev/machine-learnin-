df = df[['id', 'title', 'genres', 'keywords',
         'overview', 'cast', 'crew']]

df.head()

df.dropna(subset=['title'], inplace=True)

df['overview'] = df['overview'].fillna('')
df['genres'] = df['genres'].fillna('[]')
df['keywords'] = df['keywords'].fillna('[]')
df['cast'] = df['cast'].fillna('[]')
df['crew'] = df['crew'].fillna('[]')

df.reset_index(drop=True, inplace=True)

def convert(obj):
    try:
        data = ast.literal_eval(obj)
        return [i['name'] for i in data]
    except:
        return []

df['genres'] = df['genres'].apply(convert)
df['keywords'] = df['keywords'].apply(convert)

def get_cast(obj):
    try:
        data = ast.literal_eval(obj)
        return [i['name'] for i in data[:3]]
    except:
        return []

df['cast'] = df['cast'].apply(get_cast)

def get_director(obj):
    try:
        data = ast.literal_eval(obj)

        for i in data:
            if i['job'] == 'Director':
                return [i['name']]

        return []
    except:
        return []

df['crew'] = df['crew'].apply(get_director)

df['overview'] = df['overview'].apply(
    lambda x: x.lower().split()
)

df['genres'] = df['genres'].apply(
    lambda x: [i.replace(" ", "") for i in x]
)

df['keywords'] = df['keywords'].apply(
    lambda x: [i.replace(" ", "") for i in x]
)

df['cast'] = df['cast'].apply(
    lambda x: [i.replace(" ", "") for i in x]
)

df['crew'] = df['crew'].apply(
    lambda x: [i.replace(" ", "") for i in x]
)

df['tags'] = (
    df['overview'] +
    df['genres'] +
    df['keywords'] +
    df['cast'] +
    df['crew']
)

new_df = df[['id', 'title', 'tags']].copy()

new_df['tags'] = new_df['tags'].apply(
    lambda x: " ".join(x)
)

new_df.head()

cv = CountVectorizer(
    max_features=5000,
    stop_words='english'
)

vectors = cv.fit_transform(new_df['tags'])

def recommend(movie):

    movie = movie.lower()

    matches = new_df[
        new_df['title'].str.lower() == movie
    ]

    if matches.empty:
        print("Movie not found!")
        return

    movie_index = matches.index[0]

    distances = cosine_similarity(
        vectors[movie_index],
        vectors
    ).flatten()

    movie_list = sorted(
        enumerate(distances),
        key=lambda x: x[1],
        reverse=True
    )[1:11]

    print("Recommended Movies:")

    for i, score in movie_list:
        print(new_df.iloc[i]['title'])

recommend('Avatar')

